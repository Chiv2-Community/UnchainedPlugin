//! Consumer-defined selection keys and resolver restrictions.

use std::any::{Any, TypeId};
use std::cell::RefCell;
use std::collections::HashMap;
use std::sync::Arc;
use patternsleuth::{image::Image, resolvers::{AsyncContext, ResolverFactory, DynResolverFactory, Resolution}};
use patternsleuth::resolvers::futures::future::{BoxFuture, join_all};

/// A fieldless enum used to select resolver behavior.
///
/// Use [`crate::resolver_selection_key`] to validate the declaration and implement
/// this trait. Keys have no built-in default or process-global state.
/// `#[resolver_selection_key(require = [Variant, ...])]` exposes typed [`Self::REQUIRED`]
/// metadata and requires those keys in every enum-keyed resolver dictionary.
/// `fallback = Variant` supplies a terminal default fallback for its provider.
///
/// ```
/// #[unchained_macros::resolver_selection_key]
/// enum Mode { Read, Write }
/// # impl unchained_macros::ResolverSelector for Mode {
/// #     fn current() -> Self { Self::Read }
/// # }
/// assert!(unchained_macros::supports_selection("unrestricted", Mode::Read));
/// ```
///
/// ```
/// #[unchained_macros::resolver_selection_key(require = [Read, Write])]
/// enum Mode { Read, Write, Shared }
/// impl unchained_macros::ResolverSelector for Mode {
///     fn current() -> Self { Self::Read }
/// }
/// unchained_macros::define_pattern_resolver!(ReadOnly, {
///     Mode::Read: ["AA BB"], Mode::Write: None,
/// });
/// fn main() {
///     assert!(<Mode as unchained_macros::SelectionKey>::REQUIRED == [Mode::Read, Mode::Write]);
/// }
/// ```
///
/// Payloads and generics are rejected:
/// ```compile_fail
/// #[unchained_macros::resolver_selection_key]
/// enum Mode { Value(u8) }
/// ```
/// ```compile_fail
/// #[unchained_macros::resolver_selection_key]
/// enum Mode<const N: usize> { Value }
/// ```
pub trait SelectionKey: Copy + Eq + Send + Sync + 'static {
    /// Keys every dictionary must explicitly cover with patterns or `None`.
    /// Configure through `#[resolver_selection_key(require = [Variant, ...])]`.
    const REQUIRED: &'static [Self] = &[];
    fn name(self) -> &'static str;
    /// Default terminal fallback generated by `resolver_selection_key`.
    fn default_fallback(self) -> Option<Self> { None }
}

/// Project-owned selector state and fallback policy.
/// `current` is read once per captured session, not once per resolver.
pub trait ResolverSelector: SelectionKey {
    fn current() -> Self;
    fn fallback(self) -> Option<Self> { self.default_fallback() }
}

/// Stable, serialized cache identity. Provider or policy changes invalidate it.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]
pub struct SelectorIdentity {
    pub provider: String,
    pub value: String,
    pub fallback: Vec<String>,
    pub required: Vec<String>,
}

#[derive(Clone)]
struct CapturedSelector {
    value: Arc<dyn Any + Send + Sync>,
    fallback: Vec<Arc<dyn Any + Send + Sync>>,
    identity: SelectorIdentity,
}

impl CapturedSelector {
    fn new<E: ResolverSelector>(value: E) -> Result<Self, String> {
        let mut chain = vec![value];
        let mut current = value;
        while let Some(next) = current.fallback() {
            if chain.contains(&next) {
                return Err(format!("Selector {} has a fallback cycle at {}", std::any::type_name::<E>(), next.name()));
            }
            chain.push(next);
            current = next;
        }
        Ok(Self {
            value: Arc::new(value),
            fallback: chain.iter().skip(1).map(|key| Arc::new(*key) as Arc<dyn Any + Send + Sync>).collect(),
            identity: SelectorIdentity {
                provider: std::any::type_name::<E>().into(),
                value: value.name().into(),
                fallback: chain.iter().skip(1).map(|value| value.name().into()).collect(),
                required: E::REQUIRED.iter().map(|value| value.name().into()).collect(),
            },
        })
    }
}

#[doc(hidden)]
pub struct SelectorProvider {
    type_id: fn() -> TypeId,
    capture: fn() -> Result<CapturedSelector, String>,
}

impl SelectorProvider {
    pub const fn of<E: ResolverSelector>() -> Self {
        Self { type_id: TypeId::of::<E>, capture: || CapturedSelector::new(E::current()) }
    }

    pub const fn for_key<E: ResolverSelector>(_: E) -> Self { Self::of::<E>() }
}

inventory::collect!(SelectorProvider);

/// Immutable selector values shared by scans, cache lookup, and initialization.
#[derive(Clone, Default)]
pub struct SelectorSnapshot {
    values: Arc<HashMap<TypeId, CapturedSelector>>,
    identities: Arc<Vec<SelectorIdentity>>,
}

impl std::fmt::Debug for SelectorSnapshot {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SelectorSnapshot").field("selectors", &self.identities).finish()
    }
}

impl SelectorSnapshot {
    fn from_values(values: HashMap<TypeId, CapturedSelector>) -> Result<Self, String> {
        let mut identities: Vec<_> = values.values().map(|value| value.identity.clone()).collect();
        identities.sort();
        if identities.windows(2).any(|pair| pair[0].provider == pair[1].provider) {
            return Err("Different selector types have the same cache identity".into());
        }
        Ok(Self { values: Arc::new(values), identities: Arc::new(identities) })
    }

    pub fn capture_registered() -> Result<Self, String> {
        let mut values = HashMap::new();
        for provider in inventory::iter::<SelectorProvider> {
            if let std::collections::hash_map::Entry::Vacant(entry) = values.entry((provider.type_id)()) {
                entry.insert((provider.capture)()?);
            }
        }
        Self::from_values(values)
    }

    /// Construct an explicit snapshot without reading project state.
    pub fn from_selection<E: ResolverSelector>(value: E) -> Result<Self, String> {
        Self::from_values(HashMap::from([(TypeId::of::<E>(), CapturedSelector::new(value)?)]))
    }

    /// Add another selector without changing existing snapshots or rereading state.
    pub fn with_selection<E: ResolverSelector>(self, value: E) -> Result<Self, String> {
        let mut values = (*self.values).clone();
        if values.contains_key(&TypeId::of::<E>()) {
            return Err(format!("Selector {} is already captured", std::any::type_name::<E>()));
        }
        values.insert(TypeId::of::<E>(), CapturedSelector::new(value)?);
        Self::from_values(values)
    }

    pub fn get<E: SelectionKey>(&self) -> Result<E, String> {
        self.values.get(&TypeId::of::<E>()).and_then(|value| value.value.downcast_ref::<E>())
            .copied().ok_or_else(|| format!("Selector {} is not captured", std::any::type_name::<E>()))
    }

    pub fn cache_key(&self) -> &[SelectorIdentity] { &self.identities }

    pub fn chain<E: SelectionKey>(&self) -> Result<Vec<E>, String> {
        let current = self.get::<E>()?;
        let captured = &self.values[&TypeId::of::<E>()];
        Ok(std::iter::once(current).chain(captured.fallback.iter()
            .map(|value| *value.downcast_ref::<E>().expect("captured selector type is consistent"))).collect())
    }

    /// Fail before filtering if any linked consumer's provider is missing.
    pub fn validate_registered(&self) -> Result<(), String> {
        for provider in inventory::iter::<SelectorProvider> {
            if !self.values.contains_key(&(provider.type_id)()) {
                return Err("Snapshot is missing a registered selector provider".into());
            }
        }
        for patch in inventory::iter::<crate::PatchRegistration> {
            if self.supports_patch(patch) && !patch.resolver.supports(self) {
                return Err(format!("Patch {} targets unavailable resolver {}", patch.name, patch.resolver.named.name));
            }
        }
        Ok(())
    }

    pub fn supports_resolver(&self, name: &str) -> bool {
        inventory::iter::<crate::DeclaredResolver>.into_iter()
            .filter(|declaration| declaration.resolver.named.name == name)
            .all(|declaration| declaration.resolver.supports(self))
    }

    pub fn supports_filter(&self, filter: &ResolverFilter) -> bool {
        self.values.get(&(filter.selector)()).is_some_and(|value|
            std::iter::once(&value.value).chain(value.fallback.iter())
                .find_map(|key| (filter.lookup)(key.as_ref())).unwrap_or(false))
    }

    pub fn supports_patch(&self, patch: &crate::PatchRegistration) -> bool {
        patch.selector.is_none_or(|selector| self.values.get(&selector())
            .is_some_and(|value| (patch.applies_to)(value.value.as_ref())))
    }

    /// Seed a fresh Patternsleuth context before any consumer runs. Context clones
    /// share its cached snapshot, including when polled from another thread.
    /// Like Patternsleuth's blocking eval, do not call this inside another executor;
    /// resolve transitive dependencies through the existing `ctx` instead.
    pub fn eval<'env, F, T: Send + Sync>(&self, image: &'env Image<'_>, f: F) -> T
    where
        F: for<'ctx> FnOnce(&'ctx AsyncContext<'env>) -> BoxFuture<'ctx, T> + Send + Sync + 'env,
    {
        let _scope = SnapshotScope(ACTIVE_SNAPSHOT.with(|active| active.replace(Some(self.clone()))));
        patternsleuth::resolvers::eval(image, |ctx| Box::pin(async move {
            context_snapshot(ctx).await.expect("explicit snapshot seed must be available");
            f(ctx).await
        }))
    }

    pub fn resolve_many(&self, image: &Image<'_>, resolvers: &[fn() -> &'static DynResolverFactory])
        -> Vec<patternsleuth::resolvers::Result<Arc<dyn Resolution>>>
    {
        let factories: Vec<_> = resolvers.iter().map(|resolver| resolver().factory).collect();
        self.eval(image, |ctx| Box::pin(async move {
            join_all(factories.into_iter().map(|factory| factory(ctx))).await
        }))
    }
}

// Patternsleuth has no user-data setter. This scope only seeds a new context;
// resolver execution reads the snapshot cached in that context, not this TLS.
thread_local! {
    static ACTIVE_SNAPSHOT: RefCell<Option<SelectorSnapshot>> = const { RefCell::new(None) };
}
struct SnapshotScope(Option<SelectorSnapshot>);
impl Drop for SnapshotScope {
    fn drop(&mut self) { ACTIVE_SNAPSHOT.with(|active| active.replace(self.0.take())); }
}
static SNAPSHOT: ResolverFactory<SelectorSnapshot> = ResolverFactory {
    name: "SelectorSnapshot",
    factory: |_| Box::pin(async {
        ACTIVE_SNAPSHOT.with(|active| active.borrow().clone())
            .map_or_else(SelectorSnapshot::capture_registered, Ok)
            .map_err(patternsleuth::resolvers::ResolveError::new_msg)
    }),
};

#[doc(hidden)]
pub async fn context_snapshot(ctx: &AsyncContext<'_>) -> patternsleuth::resolvers::Result<Arc<SelectorSnapshot>> {
    ctx.resolve(&SNAPSHOT).await
}

/// Compile-time resolver identity and applicability.
pub trait ResolverDeclaration {
    const NAME: &'static str;
    const UNRESTRICTED: bool;
    const DESCRIPTOR: &'static crate::ResolverDescriptor;
}

/// Typed applicability metadata. Empty policies mean unrestricted coverage.
pub trait ResolverSelection<E: SelectionKey>: ResolverDeclaration {
    const SELECTIONS: &'static [(E, bool)];
}

#[doc(hidden)]
pub const fn resolver_selections<R: ResolverSelection<E>, E: SelectionKey>(_: E) -> &'static [(E, bool)] {
    R::SELECTIONS
}

/// Restrict a resolver and its hooks/patches by a typed selection key.
pub struct ResolverFilter {
    pub selector: fn() -> TypeId,
    pub lookup: fn(&dyn Any) -> Option<bool>,
}

/// Ad hoc single-provider query. Startup should use one frozen `SelectorSnapshot`.
/// A restriction for a different enum fails closed, never comparing discriminants.
pub fn supports_selection<E: ResolverSelector>(name: &str, selection: E) -> bool {
    SelectorSnapshot::from_selection(selection).is_ok_and(|snapshot| snapshot.supports_resolver(name))
}

#[doc(hidden)]
pub fn dictionary_allows<E: SelectionKey>(selection: &dyn Any, entries: &[(E, bool)]) -> bool {
    selection.downcast_ref::<E>().is_some_and(|value|
        entries.iter().find(|(key, _)| key == value).is_none_or(|(_, enabled)| *enabled))
}

#[doc(hidden)]
pub fn dictionary_lookup<E: SelectionKey>(selection: &dyn Any, entries: &[(E, bool)]) -> Option<bool> {
    selection.downcast_ref::<E>().and_then(|value|
        entries.iter().find(|(key, _)| key == value).map(|(_, enabled)| *enabled))
}

#[doc(hidden)]
pub fn selection_matches<E: SelectionKey>(selection: &dyn Any, expected: E) -> bool {
    selection.downcast_ref::<E>().is_some_and(|value| *value == expected)
}

#[doc(hidden)]
pub fn selection_key<E: SelectionKey>(selection: E) -> E {
    selection
}

#[doc(hidden)]
pub const fn selector_type<E: SelectionKey>(_: E) -> fn() -> TypeId { TypeId::of::<E> }
