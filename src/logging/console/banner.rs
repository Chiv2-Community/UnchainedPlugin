#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn banner_has_top_padding_and_indented_artwork() {
        let mut title = TITLE.lines();
        let blank = title.next().unwrap();
        assert!(blank.chars().all(|ch| ch == ' '));
        let artwork: Vec<_> = title.chain(SUBTITLE.lines()).collect();
        assert_eq!(artwork.len(), 17);
        assert!(artwork.iter().all(|line| line.starts_with(' ')));
        assert_eq!(blank.len(), artwork.iter().map(|line| line.chars().count()).max().unwrap());
        assert!(!SUBTITLE.ends_with('\n'), "the final newline must follow the palette reset");
    }
}
